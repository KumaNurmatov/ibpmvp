/**
 * Цвета изделия: у заказа их бывает и один, и девять оттенков. Каждый — это
 * название, как его пишет заказчик («чёрно-белая клетка»), и оттенок для
 * метки. Оттенок подбирается по названию, а если не угадался — его ставят
 * руками в карточке.
 */
const escapeHtml = (s) => String(s ?? "").replace(/[&<>"']/g, (ch) =>
  ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[ch]));

// Основа слова → оттенок. Ищется основа, стоящая в названии раньше всех:
// у «серо-бежевой» цвет серый, а не бежевый; при равенстве — самая длинная,
// чтобы «серебристый» не стал серым, а «тёмно-синий» — просто синим.
const STEMS = [
  ["черн", "#1c1c1c"], ["бел", "#f7f7f7"], ["серебр", "#c0c0c0"], ["сер", "#9a9a9a"],
  ["графит", "#3d4045"], ["антрац", "#33363a"], ["темно-син", "#1f2f63"], ["син", "#2f5fcf"],
  ["голуб", "#8ec5ea"], ["индиго", "#3b3f8f"], ["джинс", "#4f6f9a"], ["бирюз", "#3cbcb4"],
  ["мят", "#a8e0c8"], ["изумруд", "#1f8a5a"], ["зел", "#3f9b4f"], ["олив", "#7d7a3e"],
  ["хаки", "#8b8656"], ["лаванд", "#b7a3e3"], ["сирен", "#b08ad6"], ["фиолет", "#7446b8"],
  ["бордо", "#7b1f33"], ["вишн", "#8e1f3a"], ["малин", "#c4245e"], ["красн", "#d33a3a"],
  ["розов", "#ef9cbc"], ["пудр", "#e9c3bf"], ["персик", "#f6b98f"], ["оранж", "#ef7d2d"],
  ["горчич", "#c99a2e"], ["желт", "#f0cf3a"], ["лимон", "#f2e35a"], ["золот", "#d4af37"],
  ["молоч", "#f4eedf"], ["сливоч", "#f1e6cc"], ["айвори", "#f3ecdc"], ["крем", "#efe2c4"], ["беж", "#d8c3a0"],
  ["песоч", "#d9bf8c"], ["капуч", "#a88b72"], ["шоколад", "#5a3a26"], ["корич", "#7b4b2a"],
  ["экрю", "#efe6d2"], ["фисташ", "#a9d39e"], ["леопард", "#b08a5a"], ["васил", "#4a6fe3"],
  ["пурпур", "#8e2a7a"], ["кофе", "#6f4e37"],
];

/** Оттенок по названию цвета; "" — если название ни на что не похоже. */
export function guessHex(name) {
  const text = String(name || "").toLowerCase().replace(/ё/g, "е");
  let best = null;
  for (const [stem, hex] of STEMS) {
    const at = text.indexOf(stem);
    if (at < 0) continue;
    if (!best || at < best.at || (at === best.at && stem.length > best.stem.length)) {
      best = { at, stem, hex };
    }
  }
  return best ? best.hex : "";
}

/** Цвета из записи заказа: пустые строки, добавленные «на всякий случай», выпадают. */
export function normalizeColors(list) {
  return (Array.isArray(list) ? list : [])
    .filter((c) => String(c?.name || "").trim() || c?.hex)
    .map((c) => ({ name: String(c.name || "").trim(), hex: /^#[0-9a-f]{6}$/i.test(c.hex || "") ? c.hex : "" }));
}

/**
 * Список цветов в карточке заказа: столбиком, кружок своего цвета и
 * название. Оттенок не задан — берётся по названию. Когда оттенков больше
 * четырёх, список ложится в две колонки: девять строк иначе вытянули бы
 * карточку вдвое.
 */
export function colorList(colors) {
  const list = normalizeColors(colors);
  if (!list.length) return "";
  return `<ul class="colors${list.length > 4 ? " many" : ""}">${list.map((c) => {
    const hex = c.hex || guessHex(c.name);
    return `<li title="${escapeHtml(c.name)}"><i class="${hex ? "" : "none"}"${
      hex ? ` style="--c:${hex}"` : ""}></i><span>${escapeHtml(c.name)}</span></li>`;
  }).join("")}</ul>`;
}
